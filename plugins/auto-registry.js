/**
 * auto-registry.js — Vite Plugin (3-Level Hierarchy)
 *
 * Auto-discovers content from public/data/ folder structure:
 *
 *   Level 1 — COURSE (Subject):  public/data/<emoji Name>/
 *   Level 2 — SECTION (Chapter): public/data/<Course>/CH<N>-<Title>/
 *   Level 3 — LESSON:            public/data/<Course>/CH<N>-<Title>/<N>/<Title>.md
 *
 * Conventions:
 *   • Course folder: emoji prefix = icon, rest = name
 *     "🧠 Deep Learning" → icon: "🧠", name: "Deep Learning"
 *
 *   • Section folder: "CH<N>-<Title>" format
 *     "CH1-SSD" → order: 1, title: "SSD"
 *     "CH3-Gradient Descent & SGD" → order: 3, title: "Gradient Descent & SGD"
 *
 *   • Lesson folder: numeric name, contains one .md file
 *     "1/SSD Walkthrough.md" → order: 1, title: "SSD Walkthrough"
 *
 *   • Images: placed in lesson folder as images/ (relative paths in MD work automatically)
 *
 * Output: src/generated-registry.js (auto-imported by main.js)
 */
import fs from 'fs';
import path from 'path';

const DATA_DIR = 'public/data';
const OUTPUT_FILE = 'src/generated-registry.js';

// ── Helpers ──

/** Match leading emoji(s) + optional space from folder name */
const EMOJI_REGEX = /^(\p{Emoji_Presentation}|\p{Emoji}\uFE0F)\s*/u;

/** Match CHN- or CHN_ prefix for section ordering */
const SECTION_REGEX = /^CH(\d+)\s*[-_]\s*/i;

function parseCourseName(folderName) {
  const match = folderName.match(EMOJI_REGEX);
  if (match) {
    return {
      icon: match[0].trim(),
      name: folderName.slice(match[0].length).trim()
    };
  }
  return { icon: '📁', name: folderName };
}

function parseSectionName(folderName) {
  const match = folderName.match(SECTION_REGEX);
  if (match) {
    return {
      order: parseInt(match[1]),
      title: folderName.slice(match[0].length).trim()
    };
  }
  // Fallback: no CH prefix, use folder name as-is
  return { order: 999, title: folderName };
}

function slugify(str) {
  return str
    .toLowerCase()
    .replace(/[^\w\s-]/g, '')
    .trim()
    .replace(/[\s_]+/g, '-')
    .replace(/-+/g, '-');
}

function getDirs(dirPath) {
  if (!fs.existsSync(dirPath)) return [];
  return fs.readdirSync(dirPath, { withFileTypes: true })
    .filter(d => d.isDirectory())
    .map(d => d.name);
}

function getMdFiles(dirPath) {
  if (!fs.existsSync(dirPath)) return [];
  return fs.readdirSync(dirPath)
    .filter(f => f.endsWith('.md'))
    .sort();
}

// ── Scanner ──

function scanRegistry(rootDir) {
  const dataPath = path.resolve(rootDir, DATA_DIR);
  if (!fs.existsSync(dataPath)) return [];

  const subjects = [];

  // Level 1: Courses (subject folders)
  const courseFolders = getDirs(dataPath).sort();

  for (const courseFolder of courseFolders) {
    const { icon, name: courseName } = parseCourseName(courseFolder);
    const courseId = slugify(courseName) || 'course';
    const coursePath = path.join(dataPath, courseFolder);

    // Level 2: Sections (CHN-Title folders)
    const sectionFolders = getDirs(coursePath)
      .map(f => ({ folder: f, ...parseSectionName(f) }))
      .sort((a, b) => a.order - b.order);

    const chapters = []; // Flat list with section grouping

    for (const section of sectionFolders) {
      const sectionPath = path.join(coursePath, section.folder);

      // Level 3: Lessons (numbered folders with .md)
      const lessonFolders = getDirs(sectionPath)
        .filter(f => /^\d+$/.test(f))
        .sort((a, b) => parseInt(a) - parseInt(b));

      for (const lessonNum of lessonFolders) {
        const lessonPath = path.join(sectionPath, lessonNum);
        const mdFiles = getMdFiles(lessonPath);
        if (mdFiles.length === 0) continue;

        const mdFile = mdFiles[0];
        const lessonTitle = mdFile.replace(/\.md$/i, '').replace(/_/g, ' ');
        const chapterId = `${courseId}-ch${section.order}-${lessonNum}`;

        // URL-encode folder names for fetch compatibility
        const encodedCourse = encodeURIComponent(courseFolder);
        const encodedSection = encodeURIComponent(section.folder);
        const encodedMd = encodeURIComponent(mdFile);

        const relativePath = `./data/${encodedCourse}/${encodedSection}/${lessonNum}/${encodedMd}`;

        chapters.push({
          id: chapterId,
          section: section.title,
          sectionOrder: section.order,
          lessonOrder: parseInt(lessonNum),
          title: lessonTitle,
          file: relativePath
        });
      }
    }

    if (chapters.length > 0) {
      subjects.push({
        id: courseId,
        name: courseName,
        icon,
        chapters
      });
    }
  }

  return subjects;
}

function generateRegistryFile(subjects, rootDir) {
  const code = `// ⚠️ AUTO-GENERATED by plugins/auto-registry.js — Do not edit manually!
// Scanned from public/data/ folder structure at build/dev time.
//
// To add content, just create folders:
//   Course:  public/data/<emoji Name>/           (e.g. "🧠 Deep Learning")
//   Section: public/data/<Course>/CH<N>-<Title>/  (e.g. "CH3-Transformers")
//   Lesson:  public/data/<Course>/<Section>/<N>/   (e.g. "1/My Lesson.md")
//
// Restart dev server (or it auto-detects) — no code changes needed!

export const subjects = ${JSON.stringify(subjects, null, 2)};
`;
  const outPath = path.resolve(rootDir, OUTPUT_FILE);

  // Only write if changed (prevent HMR loops)
  const existing = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf-8') : '';
  if (existing !== code) {
    fs.writeFileSync(outPath, code, 'utf-8');
    const totalLessons = subjects.reduce((n, s) => n + s.chapters.length, 0);
    const totalSections = subjects.reduce((n, s) => {
      const unique = new Set(s.chapters.map(c => c.section));
      return n + unique.size;
    }, 0);
    console.log(`📁 Auto-registry: ${subjects.length} courses, ${totalSections} sections, ${totalLessons} lessons`);
  }
}

/**
 * Vite plugin: auto-discovers subjects/chapters/lessons from public/data/ folder structure.
 */
export default function autoRegistry() {
  let rootDir = '';

  return {
    name: 'auto-registry',

    configResolved(config) {
      rootDir = config.root;
    },

    buildStart() {
      const subjects = scanRegistry(rootDir);
      generateRegistryFile(subjects, rootDir);
    },

    configureServer(server) {
      const dataPath = path.resolve(rootDir, DATA_DIR);

      server.watcher.on('all', (event, filePath) => {
        if (filePath.startsWith(dataPath) && ['add', 'unlink', 'addDir', 'unlinkDir'].includes(event)) {
          const subjects = scanRegistry(rootDir);
          generateRegistryFile(subjects, rootDir);
        }
      });
    }
  };
}
